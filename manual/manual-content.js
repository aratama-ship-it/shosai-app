/* 見出し・言い換え語と（noindex でない節の）本文を、章順・節順で引く。
 * DOM に依存させず、冊子とアプリ内検索が同じ判定を使えるようにする。 */
window.MANUAL_FIND = function (query) {
  const normalized = String(query == null ? "" : query)
    .trim()
    .toLowerCase()
    .normalize("NFKC");
  if (!normalized) return [];

  const words = normalized.split(/[\s\u3000]+/).filter(Boolean);
  const hits = [];
  window.MANUAL_CONTENT.chapters.forEach((chapter) => {
    chapter.sections.forEach((section) => {
      const body = section.noindex ? "" : section.html.replace(/<[^>]*>/g, " ");
      const haystack = [section.title, ...(section.keywords || []), body]
        .join(" ")
        .toLowerCase()
        .normalize("NFKC");
      if (words.every((word) => haystack.includes(word))) hits.push(section.id);
    });
  });
  return hits;
};
