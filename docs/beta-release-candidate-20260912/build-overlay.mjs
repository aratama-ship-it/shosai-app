import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const releaseDir = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(releaseDir, "../..");
const manifest = JSON.parse(fs.readFileSync(path.join(releaseDir, "manifest.json"), "utf8"));
const sha256 = (value) => crypto.createHash("sha256").update(value).digest("hex");
const textExtensions = new Set([".html", ".js", ".css", ".webmanifest"]);

const routesFor = (relative) => {
  const route = `/${relative}`;
  if (relative === "index.html") return ["/", "/index.html"];
  if (relative === "stage.html") return ["/stage", "/stage.html"];
  if (relative === "study.html") return ["/study", "/study.html"];
  if (relative === "study-frame.html") return ["/study-frame", "/study-frame.html"];
  if (relative === "manual/manual.html") return [route, "/manual/manual"];
  if (relative === "manual/quick.html") return [route, "/manual/quick"];
  if (relative === "manual/quick-en.html") return [route, "/manual/quick-en"];
  return [route];
};

const contentType = (relative) => {
  if (relative.endsWith(".js")) return "application/javascript; charset=utf-8";
  if (relative.endsWith(".css")) return "text/css; charset=utf-8";
  if (relative.endsWith(".webmanifest")) return "application/manifest+json; charset=utf-8";
  return "text/html; charset=utf-8";
};

// 画像・PDFと本人用ショーは、現在のASSETS bindingにある配信済みバイトを保持する。
// 本日の本体・Viewerが実行するテキスト資源だけを、同一Workerへ凍結して重ねる。
const inputs = manifest.inputs.filter((item) => item.role === "browser-asset"
  && textExtensions.has(path.extname(item.path))
  && item.path !== "stage-shows.local.js");
const assets = {};
for (const item of inputs) {
  const body = fs.readFileSync(path.join(repo, item.path), "utf8");
  if (sha256(body) !== item.sha256) throw new Error(`manifest生成後に変わった資源があります: ${item.path}`);
  for (const route of routesFor(item.path)) assets[route] = [contentType(item.path), body, item.path];
}

const wrapper = `// Generated by build-overlay.mjs. Deploy only with keep_assets=true.\n`
  + `import app from "../../worker.js";\n`
  + `export { SessionRoom } from "../../session-room.js";\n`
  + `export { StudyLinks } from "../../study-links.js";\n`
  + `export { StudyReaderAuth } from "../../study-reader-auth.js";\n`
  + `export { StudyReaderAccount } from "../../study-reader-account.js";\n`
  + `export { UsageMetrics } from "../../usage-metrics.js";\n\n`
  + `export const BETA_RELEASE_ASSETS = ${JSON.stringify(assets)};\n`
  + `function releaseEnv(env) {\n`
  + `  const retainedAssets = env.ASSETS;\n`
  + `  return { ...env, STAGE_RELEASE_SCOPE: "beta-20260912", STAGE_USAGE_ENABLED: "false", STUDY_ALLOW_ANONYMOUS: "true",\n`
  + `    ASSETS: { async fetch(request) {\n`
  + `      const url = new URL(request.url);\n`
  + `      const item = (request.method === "GET" || request.method === "HEAD") && BETA_RELEASE_ASSETS[url.pathname];\n`
  + `      if (item) return new Response(request.method === "HEAD" ? null : item[1], { headers: {\n`
  + `        "Content-Type": item[0], "Cache-Control": "no-cache", "X-Stage-Beta-Release": "selected-five-viewer-20260912" } });\n`
  + `      const headers = new Headers(request.headers); headers.delete("X-Stage-Study-Asset");\n`
  + `      return retainedAssets.fetch(new Request(request, { headers }));\n`
  + `    } } };\n`
  + `}\n\n`
  + `export default { async fetch(request, env, ctx) { return app.fetch(request, releaseEnv(env), ctx); } };\n`;

fs.writeFileSync(path.join(releaseDir, "beta-overlay-worker.js"), wrapper);
const overlay = {
  release: "selected-five-viewer-20260912",
  status: "built-not-deployed",
  sourceManifestSha256: sha256(fs.readFileSync(path.join(releaseDir, "manifest.json"))),
  textAssets: inputs.map((item) => ({ path: item.path, bytes: item.bytes, sha256: item.sha256, routes: routesFor(item.path) })),
  retainedAssets: "Existing binary/manual media, private show data, and unrelated owner-app assets remain in the current ASSETS binding.",
  forcedConfiguration: { STAGE_RELEASE_SCOPE: "beta-20260912", STAGE_USAGE_ENABLED: "false", STUDY_ALLOW_ANONYMOUS: "true" },
  workerSourceBytes: Buffer.byteLength(wrapper),
  workerSourceSha256: sha256(wrapper),
};
fs.writeFileSync(path.join(releaseDir, "overlay-manifest.json"), `${JSON.stringify(overlay, null, 2)}\n`);
console.log(JSON.stringify({ release: overlay.release, textAssets: overlay.textAssets.length, workerSourceBytes: overlay.workerSourceBytes }));
