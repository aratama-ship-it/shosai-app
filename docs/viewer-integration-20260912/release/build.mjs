import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const releaseDir = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(releaseDir, '../../..');
const read = (file) => fs.readFileSync(path.join(repo, file), 'utf8');
const digest = (value) => crypto.createHash('sha256').update(value).digest('hex');

const directAssets = [
  // Keep the actual Stage Sketch entry points in the overlay too.  The Viewer
  // itself already shipped from this adapter, but the owner-side button that
  // issues its link lives in the authenticated editor shell.
  ['index.html', ['/', '/index.html']],
  ['stage.html', ['/stage', '/stage.html']],
  ['stage-session.js', ['/stage-session.js']],
  ['stage-study-owner.js', ['/stage-study-owner.js']],
  ['stage-study.css', ['/stage-study.css']],
  ['stage-sw.js', ['/stage-sw.js']],
  ['study.html', ['/study', '/study.html']],
  ['study-frame.html', ['/study-frame', '/study-frame.html']],
  ['stage-study-viewer.js', ['/stage-study-viewer.js']],
  ['stage-study-frame.js', ['/stage-study-frame.js']],
  ['stage-study-pen.js', ['/stage-study-pen.js']],
  ['stage-study-private.js', ['/stage-study-private.js']],
  ['stage-study-sync.js', ['/stage-study-sync.js']],
  ['stage-study-continuity.js', ['/stage-study-continuity.js']],
  ['stage-study-sticky.js', ['/stage-study-sticky.js']],
  ['stage-study.css', ['/stage-study.css']],
  ['stage-study-phone.css', ['/stage-study-phone.css']],
  ['stage-study-phone.js', ['/stage-study-phone.js']],
  ['stage-study-navigation.css', ['/stage-study-navigation.css']],
  ['stage-study-navigation.js', ['/stage-study-navigation.js']],
];
const frameAssets = [
  'style.css', 'stage-venues.js', 'stage-venue-lines.js', 'stage-i18n.js',
  'stage-set-model.js', 'stage-machinery.js', 'stage-sketch.js',
];
const contentType = (filename) => filename.endsWith('.js')
  ? 'application/javascript; charset=utf-8'
  : filename.endsWith('.css') ? 'text/css; charset=utf-8' : 'text/html; charset=utf-8';

const assets = {};
const manifest = [];
for (const [filename, paths] of directAssets) {
  const body = read(filename);
  manifest.push({ filename, mode: 'viewer', bytes: Buffer.byteLength(body), sha256: digest(body) });
  for (const pathname of paths) assets[pathname] = [contentType(filename), body];
}
for (const filename of frameAssets) {
  const body = read(filename);
  manifest.push({ filename, mode: 'frame', bytes: Buffer.byteLength(body), sha256: digest(body) });
  assets[`frame:${`/${filename}`}`] = [contentType(filename), body];
}

const wrapper = `// Generated by build.mjs; deploy only with --keep-assets.\n`
  + `import app from '../../../worker.js';\n`
  + `export { StudyReaderAuth } from '../../../study-reader-auth.js';\n`
  + `export { StudyReaderAccount } from '../../../study-reader-account.js';\n`
  + `export { StudyLinks } from '../../../study-links.js';\n`
  + `export { SessionRoom } from '../../../session-room.js';\n`
  + `export { UsageMetrics } from '../../../usage-metrics.js';\n\n`
  + `const VIEWER_RELEASE_ASSETS = ${JSON.stringify(assets)};\n`
  + `function viewerReleaseEnv(env) {\n`
  + `  const originalAssets = env.ASSETS;\n`
  + `  return { ...env, ASSETS: { async fetch(request) {\n`
  + `    const url = new URL(request.url);\n`
  + `    const key = request.headers.get('X-Stage-Study-Asset') === '1' ? 'frame:' + url.pathname : url.pathname;\n`
  + `    const item = (request.method === 'GET' || request.method === 'HEAD') && VIEWER_RELEASE_ASSETS[key];\n`
  + `    if (item) return new Response(request.method === 'HEAD' ? null : item[1], { headers: { 'Content-Type': item[0], 'Cache-Control': 'no-cache', 'X-Stage-Viewer-Release': '20260912' } });\n`
  + `    const headers = new Headers(request.headers); headers.delete('X-Stage-Study-Asset');\n`
  + `    return originalAssets.fetch(new Request(request, { headers }));\n`
  + `  } } };\n`
  + `}\n\n`
  + `export default { async fetch(request, env, ctx) { return app.fetch(request, viewerReleaseEnv(env), ctx); } };\n`;
fs.writeFileSync(path.join(releaseDir, 'viewer-beta-worker.js'), wrapper);

const rootConfig = read('wrangler.toml');
if (!rootConfig.includes('main = "worker.js"') || !rootConfig.includes('directory = "."')) {
  throw new Error('wrangler.toml release boundary changed; rebuild the package deliberately.');
}
const config = rootConfig
  .replace('main = "worker.js"', 'main = "viewer-beta-worker.js"')
  .replace('directory = "."', 'directory = "../../.."');
fs.writeFileSync(path.join(releaseDir, 'wrangler.viewer-beta.toml'), config);

const result = {
  release: 'viewer-beta-20260912',
  deploymentRule: 'npx wrangler deploy --config docs/viewer-integration-20260912/release/wrangler.viewer-beta.toml --keep-assets',
  retained: 'Existing authenticated beta assets remain served by the current ASSETS binding.',
  overlaid: 'Only Viewer HTML, Viewer UI assets, and iframe rendering dependencies are embedded.',
  inputs: manifest,
  workerBytes: Buffer.byteLength(wrapper),
  workerSha256: digest(wrapper),
};
fs.writeFileSync(path.join(releaseDir, 'manifest.json'), `${JSON.stringify(result, null, 2)}\n`);
console.log(JSON.stringify({ release: result.release, assets: manifest.length, workerBytes: result.workerBytes }));
